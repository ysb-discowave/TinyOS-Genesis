#ifndef TINYOS_EDITOR_H
#define TINYOS_EDITOR_H

/* ============================================================
 * TinyOS 内置全屏文本编辑器（类 nano）
 * ------------------------------------------------------------
 * 编辑在内存中的行数组上进行；保存时写回 VFS，
 * 而 VFS 在有磁盘的情况下会自动同步到 TinyFS（持久化）。
 *
 * path 为绝对路径：
 *   文件存在  -> 载入其内容
 *   文件不存在 -> 新建空缓冲，保存时创建该文件
 *   path 为 NULL/空 -> 未命名缓冲，首次保存时提示文件名
 *
 * 返回 0 = 正常退出；-1 = 无法启动
 * ============================================================ */

int editor_open(const char *path);

#endif /* TINYOS_EDITOR_H */
